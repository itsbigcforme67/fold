// a cell's twin: the same physical spot on the other side of its square (the back's frame is the front's mirror)
export const twin = c => { const f = c / NN | 0, x = c % N, y = (c / N | 0) % N; return (f ^ 1) * NN + y * N + (N - 1 - x); };
export function parseLevel(lv) {
  const s = surface(SHAPES[lv.shape]()), C = s.F * NN;
  // which sides are rooms: the shape's own, or the level's per-square list ("f", "b", "fb")
  const rooms = lv.sides ? lv.sides.flatMap((sd, i) => [...(sd.includes("f") ? [2 * i] : []), ...(sd.includes("b") ? [2 * i + 1] : [])]) : s.rooms;
  const wall = new Uint8Array(C).fill(1), target = new Uint8Array(C), box = new Uint8Array(C), btn = new Uint8Array(C);
  let player = 0, nBtn = 0;
  lv.rooms.forEach((room, k) => room.split("/").forEach((row, y) => [...row].forEach((ch, x) => {
    const c = rooms[k] * NN + y * N + x;
    wall[c] = ch === "#" ? 1 : 0;
    if ("xBP".includes(ch)) target[c] = 1;
    if ("bBO".includes(ch)) box[c] = 1;
    if ("oO".includes(ch)) btn[c] = ++nBtn;                   // buttons are numbered in room order
    if ("pP".includes(ch)) player = c;
  })));
  for (let c = 0; c < C; c++) for (let d = 0; d < 4; d++) if (!wall[c] && s.nb[c * 4 + d] < 0) wall[c] = 1;
  // links[k] = the squares button k + 1 flips (any squares, not just its own)
  // the one geometric move (shift or hinge) each square can make, from the links
  const geo = [];
  for (const a of (lv.links || []).flat()) { const [k, i, spec] = parseAct(a); if ((k === "s" || k === "h") && !geo[i]) geo[i] = spec; }
  return { s, rooms, wall, target, box, btn, links: lv.links || [], player, geo };
}

