// ---- shapes ------------------------------------------------------------------------------------------------------
const sub = (a, b) => a.map((v, i) => v - b[i]), addv = (a, b) => a.map((v, i) => v + b[i]);
const dot = (a, b) => a[0] * b[0] + a[1] * b[1] + a[2] * b[2];
const cross = (a, b) => [a[1] * b[2] - a[2] * b[1], a[2] * b[0] - a[0] * b[2], a[0] * b[1] - a[1] * b[0]];
// a square from 4 corners in order round it, turned so u x v points against nOut (seen from outside: u right, v down)
function square(p, nOut, sides = "f") {
  let u = sub(p[1], p[0]), v = sub(p[3], p[0]);
  if (dot(cross(u, v), nOut) > 0) [u, v] = [v, u];
  const n = cross(v, u), l = Math.hypot(...n);
  return { o: p[0], u, v, n: n.map(x => x / l), sides };      // sides: "f" front (outside) is a room, "b" back, "fb" both
}
const both = list => list.map(q => ({ ...q, sides: "fb" }));
// the outside of a set of unit cubes (voxels): every cube face with no cube beyond it
function polycube(vox) {
  const has = new Set(vox.map(v => v.join(","))), out = [];
  for (const p of vox) for (let a = 0; a < 3; a++) for (const sg of [-1, 1]) {
    const q = p.slice(); q[a] += sg;
    if (has.has(q.join(","))) continue;
    const b = (a + 1) % 3, c = (a + 2) % 3, base = p.slice(); if (sg > 0) base[a] += 1;
    const pt = (i, j) => { const r = base.slice(); r[b] += i; r[c] += j; return r; };
    const n = [0, 0, 0]; n[a] = sg;
    out.push(square([pt(0, 0), pt(1, 0), pt(1, 1), pt(0, 1)], n));
  }
  return out;
}
// a ring of n squares round a regular n-gon (n = 8: each meets the next at 135 degrees), rows high; open top and bottom
function band(n, rows = 1) {
  const R = 1 / (2 * Math.sin(Math.PI / n)), P = k => [R * Math.cos(2 * Math.PI * k / n), R * Math.sin(2 * Math.PI * k / n)];
  const out = [];
  for (let r = rows - 1; r >= 0; r--) for (let k = 0; k < n; k++) {
    const [x0, y0] = P(k), [x1, y1] = P(k + 1), m = Math.PI * (2 * k + 1) / n;
    out.push(square([[x0, y0, r + 1], [x1, y1, r + 1], [x1, y1, r], [x0, y0, r]], [Math.cos(m), Math.sin(m), 0]));
  }
  return out;
}
// the rhombicuboctahedron: 18 squares (6 square-on, 12 at 45 degrees) and 8 triangles, which are holes here
function rhombicuboctahedron() {
  const a = 0.5, b = 0.5 + Math.SQRT1_2, V = [];
  for (const [x, y, z] of [[a, a, b], [a, b, a], [b, a, a]]) for (const sx of [-1, 1]) for (const sy of [-1, 1]) for (const sz of [-1, 1]) V.push([sx * x, sy * y, sz * z]);
  const near = (p, q) => Math.abs(Math.hypot(...sub(p, q)) - 1) < 1e-6, out = [], seen = new Set();
  V.forEach((p, i) => V.forEach((q, j) => V.forEach((r, k) => {
    if (j >= k || !near(p, q) || !near(p, r) || Math.abs(dot(sub(q, p), sub(r, p))) > 1e-6) return;
    const s = addv(q, sub(r, p)), l = V.findIndex(t => Math.hypot(...sub(t, s)) < 1e-6);
    if (l < 0) return;
    const id = [i, j, k, l].sort((x, y) => x - y).join();
    if (seen.has(id)) return; seen.add(id);
    const n = cross(sub(q, p), sub(r, p)), c = [p, q, s, r].reduce(addv).map(x => x / 4);
    if (dot(n, c) < 0) n.forEach((x, m) => n[m] = -x);
    if (V.some(t => dot(sub(t, p), n) > 1e-6)) return;                  // a face of the solid, not a cut through it
    out.push(square([p, q, s, r], n));
  })));
  return out;
}
