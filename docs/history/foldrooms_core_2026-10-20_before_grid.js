// room cell (fx, fy) -> screen cell, the room turned by rot (screen direction s = room direction s + rot)
function toScreen(fx, fy, rot) {
  return rot === 0 ? [fx, fy] : rot === 1 ? [fy, N - 1 - fx] : rot === 2 ? [N - 1 - fx, N - 1 - fy] : [N - 1 - fy, fx];
}
function cellXY(view, c) {
  if ((c / NN | 0) !== view.f) return null;
  const [sx, sy] = toScreen(c % N, (c / N | 0) % N, view.rot);
  return [OX + sx * CELL, OY + sy * CELL];
}

function tryMove(g, sd) {
  const d = (sd + g.cam.rot) & 3, e = g.s.nb[g.p * 4 + d];
  if (e < 0) return false;
  const c1 = e >> 2, d1 = e & 3;
  if (g.wall[c1]) return false;
  let c2 = -1;
  if (g.box[c1]) {
    const e2 = g.s.nb[e];
    if (e2 < 0) return false;
    c2 = e2 >> 2;
    if (g.wall[c2] || g.box[c2]) return false;
  }
  g.hist.push({ p: g.p, box: g.box.slice(), cam: { ...g.cam }, moves: g.moves, pushes: g.pushes,
    wall: g.wall.slice(), target: g.target.slice(), btn: g.btn.slice(), flips: g.flips.slice(), turns: g.turns.slice(),
    moved: g.moved.slice(), s: g.s });
  const from = cellXY(g.cam, g.p), to = cellXY(g.cam, c1), f0 = g.cam.f, crossing = (c1 / NN | 0) !== f0;
  const texA = crossing ? roomTex(g, g.cam) : null, kind = crossing ? foldKind(g.s, f0, d) : null;
  g.anim = { t: 0, man: from && to ? [from, to] : null, box: null, boxC: c2 };
  if (c2 >= 0) {
    g.box[c1] = 0; g.box[c2] = 1; g.pushes++;
    const b2 = cellXY(g.cam, c2);
    g.anim.box = to && b2 ? [to, b2] : null;
  }
  g.p = c1; g.moves++;
  const f1 = c1 / NN | 0;
  if (f1 !== g.cam.f) { g.cam = { f: f1, rot: (d1 - sd) & 3 }; g.anim = null; }   // through a doorway
  if (c2 >= 0 && g.btn[c2]) {                             // a box onto a button: its squares flip / turn
    const acts = g.L.links[g.btn[c2] - 1] || [];
    for (const a of acts) {
      const [k, i] = parseAct(a);
      if (k === "f") flipSquare(g, i); else if (k === "r") turnSquare(g, i); else moveSquare(g, i);
    }
    // just "A ROOM TURNED" / "FLIPPED" / "SHIFTED" / "HINGED" (one after another if a button does several kinds):
    // which room, how many, or whether it was yours is for the player to work out
    const kinds = new Set(acts.map(a => parseAct(a)[0]));
    g.popQ = [...kinds].map(k => ["A ROOM", { f: "FLIPPED", r: "TURNED", s: "SHIFTED", h: "HINGED" }[k]]); g.popup = POPUP_T;
    g.anim = null;
  }
  // through a doorway at a right-angle fold (either way) or a flat join: the view turns / slides over to the next room
  if (crossing && kind) g.trans = { t: 0, sd, kind, A: texA, B: roomTex(g, g.cam) };
  return true;
}
// a square turns over: what is on each side goes to the same physical spot on the other side (you too, if you are
// in it), so doorways stay lined up with the squares round it
export function flipSquare(g, i) {
  for (let c = 2 * i * NN; c < (2 * i + 1) * NN; c++) {
    const t = twin(c);
    for (const a of [g.wall, g.target, g.btn, g.box]) [a[c], a[t]] = [a[t], a[c]];
  }
  if ((g.p / NN | 0) >> 1 === i) g.p = twin(g.p);
  if (g.cam.f >> 1 === i) g.cam = { ...g.cam, f: g.cam.f ^ 1 };
  if (g.look && g.look.f >> 1 === i) g.look = { ...g.look, f: g.look.f ^ 1 };
  g.flips[i] ^= 1;                                        // a flip (same spot, other side) and a turn commute
}
// a cell's spot after its square turns a quarter clockwise (as seen from outside): front (x, y) -> (N-1-y, x); the
// back sees the same turn anticlockwise: (x, y) -> (y, N-1-x)
export const rotCell = c => { const f = c / NN | 0, x = c % N, y = (c / N | 0) % N; return f * NN + ((f & 1) ? (N - 1 - x) * N + y : x * N + (N - 1 - y)); };
// a square turns a quarter clockwise in its own plane: both sides turn with it (you too, if you are in it), so its
// doorways move round to other edges and may or may not meet the doorways of the squares beside it
// a square shifts or hinges (its one geometric move; pressed again it goes back): it moves in 3D carrying both sides,
// boxes and you, and the joins between rooms are worked out again from the new geometry. From inside, your room looks
// the same; its doorways now meet whatever is beside it where it went.
export function moveSquare(g, i) {
  g.moved[i] ^= 1;
  g.s = surface(g.L.s.squares.map((q, j) => g.moved[j] ? geoPose(q, g.L.geo[j]) : q));
}
export function turnSquare(g, i) {
  const lo = 2 * i * NN, hi = (2 * i + 2) * NN;
  for (const a of [g.wall, g.target, g.btn, g.box]) { const old = a.slice(lo, hi); for (let c = lo; c < hi; c++) a[rotCell(c)] = old[c - lo]; }
  if ((g.p / NN | 0) >> 1 === i) g.p = rotCell(g.p);
  // seen from inside, your room holds still and the rest of the shape turns round it: the view turns with the room
  for (const k of ["cam", "look"]) {
    const v = g[k]; if (!v || v.f >> 1 !== i) continue;
    const c = v.f * NN + 2 * N + 1, [sx, sy] = toScreen(1, 2, v.rot), r = rotCell(c);
    g[k] = { ...v, rot: [0, 1, 2, 3].find(q => { const [x, y] = toScreen(r % N, (r / N | 0) % N, q); return x === sx && y === sy; }) };
  }
  g.turns[i] = (g.turns[i] + 1) & 3;
}

export function step(g, inp) {
  g.t++;
  const press = {};
  for (const k of ["a", "b"]) press[k] = inp[k] && !g.prev[k];
  KEYS.forEach((k, sd) => {                               // D-pad edges, repeating while held
    g.hold[sd] = inp[k] ? g.hold[sd] + 1 : 0;
    press[k] = g.hold[sd] === 1 || (g.hold[sd] > 10 && (g.hold[sd] - 10) % 5 === 0);
  });
  g.prev = { ...inp };
  if (g.popup) {                                          // "A ROOM TURNED" / "FLIPPED" holds everything a second
    if (--g.popup === 0 && g.popQ.length > 1) { g.popQ.shift(); g.popup = POPUP_T; }
    return;
  }
  if (g.anim && ++g.anim.t >= MOVE_T) g.anim = null;
  if (g.trans && ++g.trans.t >= TURN_T) g.trans = null;
  const busy = !!(g.anim || g.trans);
  let sd = KEYS.findIndex(k => press[k]);
  if (g.won) {
    g.won++; g.seeIn = !!inp.b;                           // B held on the reveal: see through the outsides
    // the D-pad turns the shape (two at once = diagonals); after SPIN_WAIT frames with no D-pad it eases back into
    // spinning by itself
    const h = (inp.right ? 1 : 0) - (inp.left ? 1 : 0), v = (inp.down ? 1 : 0) - (inp.up ? 1 : 0);
    if (h || v) { g.yaw += h * TURN_SPEED; g.pitch += v * TURN_SPEED; g.idle = 0; }
    else if (++g.idle > SPIN_WAIT) g.yaw += SPIN_SPEED * Math.min(1, (g.idle - SPIN_WAIT) / 30);
    if (press.a && g.won > 15) loadLevel(g, g.level + 1);
    return;
  }
  if (!busy && solved(g)) { g.won = 1; g.look = null; return; }
  g.aHold = inp.a ? g.aHold + 1 : 0;                      // A: undo; held: restart
  if (g.aHold === HOLD_RESTART) { reset(g); g.restartFlash = 20; return; }
  if (g.restartFlash) g.restartFlash--;
  if (press.a && !busy && g.hist.length) {
    const h = g.hist.pop();
    g.p = h.p; g.box = h.box; g.cam = h.cam; g.moves = h.moves; g.pushes = h.pushes; g.trans = null;
    g.wall = h.wall; g.target = h.target; g.btn = h.btn; g.flips = h.flips; g.turns = h.turns; g.moved = h.moved; g.s = h.s;
    return;
  }
  if (inp.b) {                                            // B held: peek into the room beyond an edge
    if (!g.look) g.look = { ...g.cam };
    if (sd >= 0) {
      const a = g.s.adj[g.cam.f][(sd + g.cam.rot) & 3];
      if (a) g.cam = { f: a.f, rot: (a.e + 2 - sd) & 3 };
    }
    return;
  }
  if (g.look) { g.cam = g.look; g.look = null; }
  if (sd >= 0 && busy) { g.queue = sd; return; }
  if (sd < 0 && !busy && g.queue >= 0) { sd = g.queue; g.queue = -1; }
  if (sd >= 0 && !busy) tryMove(g, sd);
}

// the demo plays the level's stored solution, then goes on to the next level
export function demo(g) {
  const sol = g.levels[g.level].sol || "";
  if (g.won) return g.won > 120 && !g.prev.a ? { a: true } : {};
  if (g.moves !== g.demoI) { reset(g); return {}; }
  if (g.popup || g.anim || g.trans || KEYS.some(k => g.prev[k]) || g.t % 3) return {};
  if (g.demoI >= sol.length) return {};
  const d = +sol[g.demoI], sd = (d - g.cam.rot) & 3;
  g.demoI++;
  return { [KEYS[sd]]: true };
}

// ---- drawing -----------------------------------------------------------------------------------------------------
const px = (b, x, y, v = 1) => { if (x >= 0 && y >= 0 && x < W && y < H) b[y * W + x] = v; };
function rect(b, x0, y0, x1, y1, v) { for (let y = y0; y <= y1; y++) for (let x = x0; x <= x1; x++) px(b, x, y, v); }
function sprite(b, x, y, spr, v = 1) { spr.forEach((r, j) => { for (let i = 0; i < r.length; i++) if (r[i] === "#") px(b, x + i, y + j, v); }); }
function text(b, x, y, s) {
  for (const ch of String(s)) { const f = F[ch] || F[" "]; for (let i = 0; i < 15; i++) if (f[i] === "1") px(b, x + i % 3, y + (i / 3 | 0)); x += 4; }
}
function line(b, x0, y0, x1, y1, dotted = false) {
  x0 = Math.round(x0); y0 = Math.round(y0); x1 = Math.round(x1); y1 = Math.round(y1);
  if (x1 < x0 || (x1 === x0 && y1 < y0)) [x0, y0, x1, y1] = [x1, y1, x0, y0];   // same pixels either way round
  const dx = Math.abs(x1 - x0), dy = -Math.abs(y1 - y0), sx = x0 < x1 ? 1 : -1, sy = y0 < y1 ? 1 : -1;
  let err = dx + dy;
  for (;;) {
    if (!dotted || !((x0 + y0) & 1)) px(b, x0, y0);
    if (x0 === x1 && y0 === y1) break;
    const e2 = 2 * err;
    if (e2 >= dy) { err += dy; x0 += sx; }
    if (e2 <= dx) { err += dx; y0 += sy; }
  }
}
function room(b, g, view, skip) {
  for (let fy = 0; fy < N; fy++) for (let fx = 0; fx < N; fx++) {
    const c = view.f * NN + fy * N + fx, [sx, sy] = toScreen(fx, fy, view.rot), x = OX + sx * CELL, y = OY + sy * CELL;
    if (g.wall[c]) {
      for (let j = 0; j < CELL; j++) for (let i = 0; i < CELL; i++)
        if (!(j === 3 || j === 6 || (j < 3 && i === 6) || (j > 3 && j < 6 && i === 2))) px(b, x + i, y + j);
      continue;
    }
    if (!g.target[c] && !g.btn[c] && !g.box[c] && c !== g.p) sprite(b, x, y, SPR.floor);
    if (g.btn[c] && !g.box[c] && c !== g.p) sprite(b, x, y, SPR.button);
    if (g.target[c] && !g.box[c]) sprite(b, x, y, SPR.target);
    if (g.box[c] && !(skip && c === skip.box)) sprite(b, x, y, g.target[c] ? SPR.boxOn : SPR.box);
    if (c === g.p && !(skip && skip.man)) sprite(b, x, y, SPR.man);
  }
}
// the reveal: the shape spinning, flat shaded, far squares first. The side of a square facing you is black with a
// green outline if it is a room, dithered if not (the back of a room, a side nobody walks on); a room's outline has
// gaps where its doorways are; the room you finished in blinks. Squares that were flipped or turned start the way the
// level began and keep moving to how they ended and back (shift / hinge, flip, turn, one after another), holding
// each way for a while. Holding B makes every square whose outward side faces
// you see-through (dotted outline only), so the inward-facing sides behind show.
const FLIP_AT = 20, FLIP_T = 40, FLIP_HOLD = 50, SPIN_SPEED = 0.035, TURN_SPEED = 0.07, SPIN_WAIT = 45;
const ease = k => k < 0.5 ? 2 * k * k : 1 - 2 * (1 - k) * (1 - k);
function moveProgress(won) {                                // 0 = as the level began, 1 = as it ended
  if (won < FLIP_AT) return 0;
  const t = (won - FLIP_AT) % (2 * (FLIP_T + FLIP_HOLD));
  if (t < FLIP_T) return t / FLIP_T;
  if (t < FLIP_T + FLIP_HOLD) return 1;
  if (t < 2 * FLIP_T + FLIP_HOLD) return 1 - (t - FLIP_T - FLIP_HOLD) / FLIP_T;
  return 0;
}
const rotAbout = (v, k, a) => { const c = Math.cos(a), s = Math.sin(a), kv = cross(k, v), d = dot(k, v); return v.map((x, i) => x * c + kv[i] * s + k[i] * d * (1 - c)); };
const lerp3 = (a, z, k) => a.map((x, i) => x + (z[i] - x) * k);
function wireframe(b, g, big = true) {
  const hasFloor = (w, f) => { for (let c = f * NN; c < (f + 1) * NN; c++) if (!w[c]) return true; return false; };
  const prog = moveProgress(g.won);
  const sq = g.s.corners, all = [...sq.flat(), ...g.L.s.corners.flat()], n = all.length;   // fit start and end
  const cen = all.reduce(addv).map(x => x / n), R = Math.max(...all.map(p => Math.hypot(...sub(p, cen))));
  const ca = Math.cos(g.yaw), sa = Math.sin(g.yaw), ct = Math.cos(g.pitch), st = Math.sin(g.pitch);
  const turn = ([x0, y0, z0]) => { const x = x0 * ca - y0 * sa, y = x0 * sa + y0 * ca; return [x, y * ct - z0 * st, y * st + z0 * ct]; };
  const D = 3 * R, k0 = (big ? 22 : 19) / R, cy = big ? 34 : 37;
  const proj = p => { const [x, y, z] = turn(sub(p, cen)), k = D / (D + y) * k0; return [32 + x * k, cy - z * k]; };
  const eye = [0, -D, 0];                                   // the camera, in turned space (depth is +y)
  // each square's pose now: a moved one goes from how the level began to how it ended, its kinds of move one after
  // another (shift / hinge, then flip, then turn); the rest are as they are
  const poses = sq.map((cNow, i) => {
    let c = cNow, n0 = g.s.faces[2 * i].n, W = g.wall, past = false;
    const kTurn = g.turns[i], fl = g.flips[i], mv = g.moved[i];
    if (kTurn || fl || mv) {
      W = g.L.wall; c = g.L.s.corners[i]; n0 = g.L.s.faces[2 * i].n;
      const ph = [mv && "g", fl && "f", kTurn && "r"].filter(Boolean), part = k => { const j = ph.indexOf(k); return j < 0 ? 0 : ease(Math.min(1, Math.max(0, prog * ph.length - j))); };
      const m = c.reduce(addv).map(v => v / 4), v = g.L.s.faces[2 * i].v, kv = v.map(x => x / Math.hypot(...v));
      const thF = Math.PI * part("f"), thR = -(kTurn === 3 ? -1 : kTurn) * Math.PI / 2 * part("r"), nAx = n0;
      c = c.map(p => addv(m, rotAbout(rotAbout(sub(p, m), kv, thF), nAx, thR)));
      n0 = rotAbout(rotAbout(n0, kv, thF), nAx, thR);
      if (mv) { const { pt, vec } = geoXform(g.L.s.squares[i], g.L.geo[i], part("g")); c = c.map(pt); n0 = vec(n0); }
      c = c.map(p => p.map(x => Math.round(x * 1e9) / 1e9));
      past = thF > Math.PI / 2;                             // swung over: see below
    }
    return { c, n0, W, past };
  });
  const order = poses.map((p, i) => [i, turn(sub(p.c.reduce(addv).map(v => v / 4), cen))[1]]).sort((p, q) => q[1] - p[1]);
  for (const [i] of order) {
    const { c, n0, W, past } = poses[i];
    const ctr = turn(sub(c.reduce(addv).map(v => v / 4), cen));
    const nT = turn(n0), front = dot(nT, sub(eye, ctr)) > 0, f = 2 * i + (front ? 0 : 1);
    const room = hasFloor(W, f), clear = g.seeIn && front, q = c.map(proj);
    if (!clear) {                                           // fill the (convex) quad: inside = same side of all 4 edges
      const xs = q.map(p => p[0]), ys = q.map(p => p[1]);
      for (let y = Math.floor(Math.min(...ys)); y <= Math.ceil(Math.max(...ys)); y++) for (let x = Math.floor(Math.min(...xs)); x <= Math.ceil(Math.max(...xs)); x++) {
        let pos = 0, neg = 0;
        for (let e = 0; e < 4; e++) {
          const [x0, y0] = q[e], [x1, y1] = q[(e + 1) & 3], cr = (x1 - x0) * (y + 0.5 - y0) - (y1 - y0) * (x + 0.5 - x0);
          if (cr > 0) pos++; else if (cr < 0) neg++;
        }
        if (pos && neg) continue;
        px(b, x, y, room ? 0 : ((x + y) & 1));
      }
    }
    // the outline in the visible side's own frame (the back's corners run TR TL BL BR), with doorway gaps. A flip in
    // the game keeps everything at its physical spot (a mirror through the square), but it is shown as a swing over
    // (a turn), which mirrors left/right: once past edge-on, each side is drawn in the other side's frame, so the
    // swing lands exactly on how the level ended.
    const K = front !== past ? c : [c[1], c[0], c[3], c[2]];
    for (let e = 0; e < 4; e++) for (let p = 0; p < N; p++) {
      const [x, y] = [[p, 0], [N - 1, p], [N - 1 - p, N - 1], [0, N - 1 - p]][e];
      if (room && !W[f * NN + y * N + x]) continue;
      const [x0, y0] = proj(lerp3(K[e], K[(e + 1) & 3], p / N)), [x1, y1] = proj(lerp3(K[e], K[(e + 1) & 3], (p + 1) / N));
      line(b, x0, y0, x1, y1, clear);
    }
    if (!clear && (g.p / NN | 0) === f && (g.t >> 3) & 1) {   // where you are
      const [x, y] = proj(c.reduce(addv).map(v => v / 4));
      rect(b, Math.round(x) - 1, Math.round(y) - 1, Math.round(x) + 1, Math.round(y) + 1, 1);
    }
  }
}
// ---- the turn between rooms -------------------------------------------------------------------------------------
// Which way face f folds into its neighbour over its edge d: "out" (an outside corner: the next room bends away, as
// over a cube's edge), "in" (an inside corner: it bends up towards you), "flat" (same plane), or null for anything
// else (45 degrees, round a rim onto a back), which just cuts.
function foldKind(s, f, d) {
  const F = s.faces[f], a = s.adj[f][d]; if (!a) return null;
  const un = v => { const l = Math.hypot(...v); return v.map(x => x / l); };
  const out = un([F.v.map(x => -x), F.u, F.v, F.u.map(x => -x)][d]), nB = s.faces[a.f].n, k = dot(nB, out);
  return k > 0.9 ? "out" : k < -0.9 ? "in" : dot(nB, F.n) > 0.9 ? "flat" : null;
}
function roomTex(g, view) { const t = new Uint8Array(W * H); room(t, g, view, null); return t; }
// The two rooms (as they look on screen) become textures on a pair of squares meeting at the fold, seen in
// perspective from in front of the room you are leaving; the pair turns about the fold's corner (behind the screen for
// an outside corner, in front of it for an inside one) or slides (flat) until the new room is where the old one was.
// Each pixel is traced to the nearest square facing it; turned-away squares are dithered and the outline and crease
// drawn. Worked out for "next room on the right"; the other ways mirror / transpose the screen and the textures.
const RH = (N * CELL) / 2, RD = 4 * RH;                    // room half size, camera distance (the room plane is 1:1)
const DITHER = [0, 8, 2, 10, 12, 4, 14, 6, 3, 11, 1, 9, 15, 7, 13, 5].map(v => (v + 0.5) / 16);
function roomTurn(b, tr) {
  const k = ease(Math.min(1, (tr.t + 1) / TURN_T)), S = 63, T = N * CELL - 1;
  const map = [(x, y, m) => [y, m - x], (x, y) => [x, y], (x, y) => [y, x], (x, y, m) => [m - x, y]][tr.sd];
  const rotY = (p, a, zc) => { const x = p[0], z = p[2] - zc; return [x * Math.cos(a) + z * Math.sin(a), p[1], -x * Math.sin(a) + z * Math.cos(a) + zc]; };
  const A0 = [[0, 0, 0], [1, 0, 0], [0, 1, 0], [0, 0, -1]];         // centre, right, down, normal (towards the camera)
  let fa, fb;
  if (tr.kind === "flat") {
    const dx = -2 * RH * k;
    fa = [[dx, 0, 0], ...A0.slice(1)]; fb = [[2 * RH + dx, 0, 0], ...A0.slice(1)];
  } else {
    const zc = tr.kind === "out" ? RH : -RH, sg = tr.kind === "out" ? 1 : -1;
    const turnF = (F, a) => [rotY(F[0], a, zc), rotY(F[1], a, 0), rotY(F[2], a, 0), rotY(F[3], a, 0)];
    fa = turnF(A0, sg * Math.PI / 2 * k); fb = turnF(turnF(A0, -sg * Math.PI / 2), sg * Math.PI / 2 * k);
  }
  const faces = [[fa, tr.A], [fb, tr.B]], id = new Uint8Array(W * H);
  for (let cy = 0; cy < H; cy++) for (let cx = 0; cx < W; cx++) {
    const d = [cx - 31.5, cy - 31.5, RD], C = [0, 0, -RD];
    let best = Infinity, hit = null;
    faces.forEach(([F, tex], i) => {
      const den = dot(d, F[3]); if (den >= 0) return;                // facing away
      const t = dot(sub(F[0], C), F[3]) / den; if (t <= 0 || t >= best) return;
      const P = addv(C, d.map(x => x * t)), q = sub(P, F[0]), sx = dot(q, F[1]), sy = dot(q, F[2]);
      if (Math.abs(sx) > RH || Math.abs(sy) > RH) return;
      best = t; hit = [i, tex, sx, sy, 0.3 + 0.7 * Math.max(0, -F[3][2])];
    });
    if (!hit) continue;
    const [i, tex, sx, sy, sh] = hit;
    const [tx, ty] = map(Math.min(T, Math.max(0, Math.floor(sx + RH))), Math.min(T, Math.max(0, Math.floor(sy + RH))), T);
    const [ox, o2] = map(cx, cy, S), oy = o2 + (OY - OX);           // the canonical screen is centred on the room
    if (oy < 0 || oy >= H) continue;
    id[oy * W + ox] = i + 1;
    if (tex[(OY + ty) * W + OX + tx] && DITHER[(oy & 3) * 4 + (ox & 3)] < sh) px(b, ox, oy);
  }
  for (let y = 0; y < H; y++) for (let x = 0; x < W; x++) {          // outline: the silhouette and the crease
    const v = id[y * W + x]; if (!v) continue;
    const o = (i, j) => (i < 0 || j < 0 || i >= W || j >= H) ? 0 : id[j * W + i];
    if (o(x - 1, y) !== v || o(x + 1, y) !== v || o(x, y - 1) !== v || o(x, y + 1) !== v) px(b, x, y);
  }
}
const lerp = (a, z, k) => Math.round(a + (z - a) * k);
