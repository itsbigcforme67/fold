// FOLD ROOMS for the VMX's 64x64 1-bit screen: Sokoban on the outside of a 3D shape made of squares (working name),
// ours; the second mode of FOLD. Every square of the shape is a full-screen 8x8 room; its outer ring is wall except
// for doorways, which can be anywhere along an edge and lead into the room on the other side of that edge, however
// the two squares meet: at a right angle (cubes, bricks, polycubes, concave corners included), or at 135 degrees (an
// octagonal ring, the rhombicuboctahedron) or anything else. An edge with no square beyond it is solid wall. Walking
// through a doorway turns the view over to the next room in 3D (an outside corner, an inside corner, or a slide when
// flat; other joins just cut), and your direction on screen stays the same. The shape is never shown while you play; clearing the level reveals it spinning, flat shaded: rooms black
// with a green outline, sides that were not rooms dithered.
// Shapes are lists of 3D squares (corner o, axes u right and v down, with u x v pointing into the shape). Either side
// of a square can be a room: walk over an open edge and you come round the lip onto the back. Rooms are joined by
// turning about each edge to the first square met (see surface()), so the adjacency is never hand-written.
// Controls: D-pad walk / push (repeats when held); A undo, hold A restart; hold B + D-pad peek into the room beyond
// that edge; on the reveal, the D-pad turns the shape (8 ways; 1.5 s after letting go it spins again), hold B to
// see through the outside, A goes on.
// Input: held keys {up, down, left, right, a, b}. 64x64 bit buffer, 30 Hz.

