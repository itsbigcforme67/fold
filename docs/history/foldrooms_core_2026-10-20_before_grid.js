function reset(g) {
  g.wall = g.L.wall.slice(); g.target = g.L.target.slice(); g.btn = g.L.btn.slice();
  g.s = g.L.s; g.flips = new Uint8Array(g.s.F >> 1); g.turns = new Uint8Array(g.s.F >> 1);   // per square: flipped?,
  g.moved = new Uint8Array(g.s.F >> 1);                                                  // quarter turns, shifted/hinged?
  g.popup = 0; g.box = g.L.box.slice(); g.p = g.L.player; g.cam = { f: g.p / NN | 0, rot: 0 }; g.look = null;
  g.yaw = 0; g.pitch = 0.5; g.idle = 999;                  // the reveal's view of the shape
  g.moves = 0; g.pushes = 0; g.hist = []; g.anim = null; g.trans = null; g.queue = -1; g.won = 0; g.demoI = 0;
}
