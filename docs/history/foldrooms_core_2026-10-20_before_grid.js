// Every square has two sides: the front (seen from outside: corner o, u right, v down) and the back (the mirror
// image: corner o + u, -u, v). A side is a "face" of the game; faces 2i and 2i + 1 are square i's front and back.
// Walking off a face's edge: turn about the edge, from the face's own half-plane towards the side its normal points
// to, and land on the first square met (on its side facing back at you). The back of your own square is met last, a
// full turn round: that is walking over an open rim onto the back. This is right for folds at any angle, concave
// ones, and edges shared by three or more squares. The join is pure geometry: a side that is not a room is simply
// all wall (so a room flipped onto it later just works). adj[f][e] = {f, e}; nb[c*4+d] = c2*4+d2 (-1 never happens
// with this rule, but is handled). isRoom / rooms = the sides the shape makes rooms by default.
export function surface(squares) {
  const key = p => p.map(x => Math.round(x * 1e5) / 1e5).join(","), seg = new Map();
  const faces = [], isRoom = [];
  squares.forEach(q => {
    const { o, u, v, n } = q;
    faces.push({ o, u, v, n }); isRoom.push(q.sides.includes("f"));
    faces.push({ o: addv(o, u), u: u.map(x => -x), v, n: n.map(x => -x) }); isRoom.push(q.sides.includes("b"));
  });
  const fc = faces.map(({ o, u, v }) => [o, addv(o, u), addv(addv(o, u), v), addv(o, v)]);
  fc.forEach((c, f) => { for (let e = 0; e < 4; e++) {
    const k = [key(c[e]), key(c[(e + 1) & 3])].sort().join("|");
    if (!seg.has(k)) seg.set(k, []); seg.get(k).push([f, e]);
  } });
  const centre = f => fc[f].reduce(addv).map(x => x / 4), norm = a => { const l = Math.hypot(...a); return a.map(x => x / l); };
  const adj = faces.map(() => [null, null, null, null]);
  fc.forEach((c, f) => { for (let e = 0; e < 4; e++) {
    const p = c[e], q = c[(e + 1) & 3], ax = norm(sub(q, p)), mid = addv(p, q).map(x => x / 2);
    const inward = f => { const d = sub(centre(f), mid); return norm(sub(d, ax.map(x => x * dot(d, ax)))); };
    const dA = inward(f), nA = faces[f].n;
    let best = null, bestPhi = Infinity;
    for (const [g] of seg.get([key(p), key(q)].sort().join("|"))) {
      if ((g >> 1) === (f >> 1) && g !== (f ^ 1)) continue;       // the face itself
      let phi;
      if (g === (f ^ 1)) phi = 2 * Math.PI;                         // own back: a full turn
      else { const d = inward(g); phi = Math.atan2(dot(d, nA), dot(d, dA)); if (phi <= 1e-9) phi += 2 * Math.PI; }
      if (phi >= bestPhi - 1e-9) continue;
      // of that square's two sides, the one facing back along the turn
      const t = addv(nA.map(x => x * Math.cos(phi)), dA.map(x => -x * Math.sin(phi)));
      bestPhi = phi; best = dot(faces[g].n, t) < 0 ? g : g ^ 1;
    }
    if (best === null) continue;
    const e2 = [0, 1, 2, 3].find(k => key(fc[best][k]) === key(q) && key(fc[best][(k + 1) & 3]) === key(p));
    if (e2 === undefined) throw new Error("faces " + f + " and " + best + " meet the wrong way round");
    adj[f][e] = { f: best, e: e2 };
  } });
  const F = faces.length, nb = new Int32Array(F * NN * 4);
  for (let c = 0; c < F * NN; c++) for (let d = 0; d < 4; d++) {
    const f = c / NN | 0, x = c % N, y = (c / N | 0) % N, nx = x + DX[d], ny = y + DY[d];
    if (nx >= 0 && ny >= 0 && nx < N && ny < N) { nb[c * 4 + d] = (f * NN + ny * N + nx) * 4 + d; continue; }
    const a = adj[f][d];
    if (!a) { nb[c * 4 + d] = -1; continue; }
    const p = [x, y, N - 1 - x, N - 1 - y][d], p2 = N - 1 - p;
    const [x2, y2] = [[p2, 0], [N - 1, p2], [N - 1 - p2, N - 1], [0, N - 1 - p2]][a.e];
    nb[c * 4 + d] = (a.f * NN + y2 * N + x2) * 4 + ((a.e + 2) & 3);
  }
  const rooms = []; isRoom.forEach((r, f) => { if (r) rooms.push(f); });
  return { F, adj, nb, squares, faces, isRoom, rooms, corners: squares.map(({ o, u, v }) => [o, addv(o, u), addv(addv(o, u), v), addv(o, v)]) };
}

// a geometric room move as a rigid motion of square q, frac of the way: "s<dir>" slides it one unit (u d l r in its
// own frame, o / i out / in along its normal); "h<edge><+|->" swings it 90 degrees about one of its edges, towards
// its outside (+) or away from it (-). Returns {pt, vec}: maps for points and for directions.
export function geoXform(q, spec, frac = 1) {
  const un = a => { const l = Math.hypot(...a); return a.map(x => x / l); };
  if (spec[0] === "s") {
    const d = { u: un(q.v).map(x => -x), d: un(q.v), l: un(q.u).map(x => -x), r: un(q.u), o: q.n, i: q.n.map(x => -x) }[spec[1]];
    const t = d.map(x => x * frac);
    return { pt: p => addv(p, t), vec: v => v };
  }
  const e = +spec[1], c = [q.o, addv(q.o, q.u), addv(addv(q.o, q.u), q.v), addv(q.o, q.v)], A = c[e], ax = un(sub(c[(e + 1) & 3], A));
  const m = c.reduce(addv).map(x => x / 4), sgn = spec[2] === "-" ? -1 : 1;
  const ang = (dot(rotAbout(sub(m, A), ax, Math.PI / 2), q.n) * sgn > 0 ? 1 : -1) * Math.PI / 2 * frac;
  return { pt: p => addv(A, rotAbout(sub(p, A), ax, ang)), vec: v => rotAbout(v, ax, ang) };
}
export function geoPose(q, spec) {
  const { pt, vec } = geoXform(q, spec);
  return { ...q, o: pt(q.o), u: vec(q.u), v: vec(q.v), n: vec(q.n) };
}
// two squares in the same place (same middle, same plane) make the joins ambiguous: levels (and the generator, and
// any editor) must never move a square onto another one. True if any pair coincides.
export function coincident(squares) {
  const key = q => [q.o, addv(q.o, q.u), addv(addv(q.o, q.u), q.v), addv(q.o, q.v)].reduce(addv).map(x => Math.round(x * 250)).join(",")
    + "|" + q.n.map(x => Math.abs(Math.round(x * 1000))).join(",");
  const seen = new Set();
  for (const q of squares) { const k = key(q); if (seen.has(k)) return true; seen.add(k); }
  return false;
}
